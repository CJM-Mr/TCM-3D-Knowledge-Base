def main():
    seed = json.load(open(SEED, encoding='utf-8'))
    # 修正 OCR 错字方名
    NAME_FIX = {'栀子甘草敱汤': '栀子甘草豉汤', '栀子生姜敱汤': '栀子生姜豉汤'}
    for f in seed['formulas']:
        if f.get('name') in NAME_FIX:
            f['name'] = NAME_FIX[f['name']]
    hit = 0
    miss = []
    for f in seed['formulas']:
        if f.get('book') != 'shanghan':
            continue
        if (f.get('eff') or '').strip():
            continue  # 已有注解，不动
        data = ENRICH.get(f['name'])
        if not data:
            miss.append(f['name'])
            continue
        for k, v in data.items():
            f[k] = v
        hit += 1

    json.dump(seed, open(SEED, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('补全方剂: %d' % hit)
    if miss:
        print('未覆盖(%d): %s' % (len(miss), '、'.join(miss)))

    fs = [f for f in seed['formulas'] if f.get('book') == 'shanghan']
    for k in ('eff', 'ind', 'ana', 'cau', 'nhx'):
        n = sum(1 for f in fs if (f.get(k) or '').strip())
        print('  %-4s 有值 %d/%d' % (k, n, len(fs)))


if __name__ == '__main__':
    main()
