_MIN_ITEM = 2          # 条目最短字数
_MAX_ITEMS = 12        # 条目最多保留数
# 舌象、脉象不属于「证候条目」，拆解时跳过
_SKIP_ITEM = re.compile(r'^(脉|舌|苔|舌苔|指纹)')


def _split_items(text):
    """把主治原文拆成条目，去重并保持原顺序"""
    out = []
    for x in _SPLIT.split(text or ''):
        x = x.strip(' 　')
        if len(x) < _MIN_ITEM or _SKIP_ITEM.match(x):
            continue
        if x not in out:
            out.append(x)
    return out[:_MAX_ITEMS]


def _split_clin(text):
    """拆临床应用：优先按 ①②③ 分条，否则按分号"""
    text = (text or '').strip()
    if not text:
        return []
    if _CIRCLED.search(text):
        parts = [p for p in _CIRCLED.split(text) if p.strip()]
    else:
        parts = [p for p in re.split(r'[；;]', text) if p.strip()]
    out = []
    for p in parts:
        p = p.strip(' 　，,。；;')
        if len(p) < 4:
            continue
        name = ''
        m = _PAREN.search(p)
        if m:
            name = m.group(1).strip()
        out.append({'text': p, 'formula': name})
    return out


def _overlap(a, b):
    """粗略相似度：两字窗口的重合个数"""
    a = a or ''
    b = b or ''
    if not a or not b:
        return 0
    n = 0
    for i in range(len(a) - 1):
        if a[i:i + 2] in b:
            n += 1
    return n


def _match_clin(item, clins):
    best = None
    best_score = 0
    for c in clins:
        s = _overlap(item, c['text']) * 2 + _overlap(item, c['formula'])
        if s > best_score:
            best_score, best = s, c
    return best if best_score >= 2 else None


def _match_eff(item, effs):
    """把证候条目对到功效上；对不上返回空串"""
    if not effs:
        return ''
    keys = []
    for pat, ks in _EFF_RULES:
        if re.search(pat, item):
            keys.extend(ks)

    best, best_score = '', 0
    for e in effs:
        s = sum(2 for k in keys if k in e) + _overlap(item, e)
        if s > best_score:
            best_score, best = s, e
    if best:
        return best

    # 没有规则命中时，退回字面重合
    best, best_score = '', 0
    for e in effs:
        s = _overlap(item, e)
        if s > best_score:
            best_score, best = s, e
    return best if best_score >= 2 else ''


def _match_combo(item, combos):
    for w, t in (combos or []):
        if _overlap(item, t) >= 2 or item in t:
            return {'h': w, 't': t}
    return None


def _uniq(seq):
    out = []
    for x in seq:
        if x and x not in out:
            out.append(x)
    return out


# ---------------------------------------------------------------- 中药
def herb(h):
    """返回 {mechanism, items[], points}"""
    ind = h.get('ind') or ''
    effs = h.get('eff') or []
    clins = _split_clin(h.get('clin'))
    combos = h.get('combo') or []
    items = _split_items(ind)

    fla = h.get('fla') or []
    nat = h.get('nat') or ''
    mer = h.get('mer') or []

    # ---- 证治机理：性味 → 五味/四气含义 → 归经 → 功效 → 主治
    seg = []
    if h.get('name'):
        head = '%s味%s' % (h['name'], '、'.join(fla)) if fla else h['name']
        if nat:
            head += '，性' + nat
        if mer:
            head += '，归' + '、'.join(mer) + '经'
        seg.append(head + '。')

    fm = _uniq([FLA_MEAN.get(x, '') for x in fla])
    nm = NAT_MEAN.get(nat, '')
    if fm or nm:
        seg.append('，'.join(fm + ([nm] if nm else [])) + '。')

    mm = _uniq([MER_MEAN.get(x, '') for x in mer])[:3]
    if mm:
        seg.append('，'.join(mm) + '。')

    if effs:
        seg.append('故能%s。' % '、'.join(effs))
    if items:
        seg.append('凡见%s，皆可据证选用。' % '、'.join(items[:6]))
    mechanism = ''.join(seg)

    # ---- 逐证解析
    rows = []
    for it in items:
        eff = _match_eff(it, effs)
        cl = _match_clin(it, clins)
        cb = _match_combo(it, combos)
        if cl or eff:
            why = ''
        else:
            # 兜底：不臆造病机，只提示「取上列功效为用」
            why = '此证亦属本品所主，取上列功效为用。'
        rows.append({
            'name': it,
            'eff': eff,
            'clin': cl['text'] if cl else '',
            'formula': cl['formula'] if cl else '',
            'combo': cb or None,
            'why': why,
        })

    # ---- 辨证要点：优先用「临床应用」首条，其次用标签
    points = ''
    if clins:
        points = clins[0]['text']
    elif h.get('tags'):
        points = '以「%s」为辨证着眼点。' % '、'.join(h['tags'][:4])

    return {'mechanism': mechanism, 'items': rows, 'points': points}


# ---------------------------------------------------------------- 方剂
def formula(f):
    """返回 {items[], sentences[], points}"""
    ind = f.get('ind') or ''
    detail = (f.get('indDetail') or f.get('ind_detail') or '').strip()
    items = _split_items(ind)

    # 病机分析按句切分，便于前端逐句排列
    sentences = [s.strip() for s in re.split(r'(?<=[。；;])', detail) if s.strip()]

    points = (f.get('apply') or '').strip()
    return {'items': items, 'sentences': sentences, 'points': points}
